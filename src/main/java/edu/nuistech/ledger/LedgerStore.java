package edu.nuistech.ledger;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.time.LocalDate;
import java.time.YearMonth;
import java.util.ArrayList;
import java.util.List;
import org.springframework.stereotype.Component;

@Component
final class LedgerStore {
    private static final String CREATE_TABLE = """
            CREATE TABLE IF NOT EXISTS expenses (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                spent_on DATE NOT NULL,
                category VARCHAR(40) NOT NULL,
                amount DECIMAL(12, 2) NOT NULL CHECK (amount > 0),
                note VARCHAR(200) NOT NULL
            )
            """;

    record Entry(long id, Expense expense) {}

    static final class StorageException extends RuntimeException {
        StorageException(Path directory, Exception cause) {
            super("Could not read or write the ledger in " + directory.toAbsolutePath().normalize() + ".", cause);
        }
    }

    void add(Path directory, Expense expense) {
        String sql = "INSERT INTO expenses (spent_on, category, amount, note) VALUES (?, ?, ?, ?)";
        try (var connection = open(directory);
                var statement = prepare(connection, sql)) {
            statement.setObject(1, expense.date());
            statement.setString(2, expense.category());
            statement.setBigDecimal(3, expense.amount());
            statement.setString(4, expense.note());
            statement.executeUpdate();
        } catch (IOException | SQLException exception) {
            throw new StorageException(directory, exception);
        }
    }

    List<Entry> list(Path directory, YearMonth month, String category) {
        String filterCategory = category == null ? null : Expense.normalizeCategory(category);
        StringBuilder sql = new StringBuilder("SELECT id, spent_on, category, amount, note FROM expenses WHERE 1 = 1");
        if (month != null) {
            sql.append(" AND spent_on BETWEEN ? AND ?");
        }
        if (filterCategory != null) {
            sql.append(" AND category = ?");
        }
        sql.append(" ORDER BY spent_on, id");

        try (var connection = open(directory);
                var statement = prepare(connection, sql.toString())) {
            int nextParameter = 1;
            if (month != null) {
                statement.setObject(nextParameter++, month.atDay(1));
                statement.setObject(nextParameter++, month.atEndOfMonth());
            }
            if (filterCategory != null) {
                statement.setString(nextParameter, filterCategory);
            }
            try (var rows = statement.executeQuery()) {
                var entries = new ArrayList<Entry>();
                while (rows.next()) {
                    var expense = new Expense(rows.getObject("spent_on", LocalDate.class),
                            rows.getString("category"), rows.getBigDecimal("amount"), rows.getString("note"));
                    entries.add(new Entry(rows.getLong("id"), expense));
                }
                return entries;
            }
        } catch (IOException | SQLException exception) {
            throw new StorageException(directory, exception);
        }
    }

    private Connection open(Path directory) throws IOException, SQLException {
        Path absolute = directory.toAbsolutePath().normalize();
        if (absolute.toString().contains(";")) {
            throw new IllegalArgumentException("Data directory names must not contain semicolons.");
        }
        Files.createDirectories(absolute);
        String url = "jdbc:h2:file:" + absolute.resolve("ledger").toString().replace('\\', '/');
        return DriverManager.getConnection(url);
    }

    private PreparedStatement prepare(Connection connection, String sql) throws SQLException {
        // Keep schema creation and the command on one connection to the embedded file.
        try (var statement = connection.createStatement()) {
            statement.execute(CREATE_TABLE);
        }
        return connection.prepareStatement(sql);
    }
}
